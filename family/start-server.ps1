# Starts the family server: login-server (minimized window) + Canary (this window).
#
# Usage (PowerShell, from the repository folder):
#     powershell -ExecutionPolicy Bypass -File family\start-server.ps1
#
# To stop: log out in the game, then press Ctrl+C in this window. Canary saves
# everyone and shuts down cleanly; the login-server is stopped afterwards.

. (Join-Path $PSScriptRoot 'lib.ps1')
$cfg = Read-LocalEnv

foreach ($exe in $CanaryExe, $LoginExe) {
	if (-not (Test-Path -LiteralPath $exe)) { Stop-Family "$exe not found. Run family\setup.ps1 first." }
}
if (-not (Test-DatabaseReady $cfg)) { Stop-Family 'The database is not reachable or not set up. Is the MariaDB service running? Otherwise run family\setup.ps1.' }

function Test-PortFree([int]$Port) {
	try {
		$l = New-Object System.Net.Sockets.TcpListener([System.Net.IPAddress]::Any, $Port)
		$l.Start(); $l.Stop(); return $true
	} catch { return $false }
}
$loginPort = [int]$cfg['LOGIN_HTTP_PORT']
foreach ($p in @($loginPort, 9090, 7171, 7172)) {
	if (-not (Test-PortFree $p)) {
		$hint = ''
		if ($p -eq $loginPort) { $hint = ' Set LOGIN_HTTP_PORT=8088 in family\local.env and change the client config.ini to http://<ip>:8088/login.php.' }
		Stop-Family "TCP port $p is already in use (is the server already running?).$hint"
	}
}

# ---------------------------------------------------------------------------
Write-Step 'Building config.lua (config.lua.dist + family overrides + local.env)'
# ---------------------------------------------------------------------------
$dist = Get-Content -LiteralPath (Join-Path $RepoRoot 'config.lua.dist') -Raw
$family = Get-Content -LiteralPath (Join-Path $FamilyDir 'config.family.lua') -Raw
$machine = @(
	'-- Generated by family\start-server.ps1 from family\local.env. Do not edit.',
	"ip = $(ConvertTo-LuaString $cfg['SERVER_IP'])",
	"serverName = $(ConvertTo-LuaString $cfg['SERVER_NAME'])",
	"mysqlHost = $(ConvertTo-LuaString $cfg['DB_HOST'])",
	"mysqlPort = $([int]$cfg['DB_PORT'])",
	"mysqlUser = $(ConvertTo-LuaString $cfg['DB_USER'])",
	"mysqlPass = $(ConvertTo-LuaString $cfg['DB_PASSWORD'])",
	"mysqlDatabase = $(ConvertTo-LuaString $cfg['DB_NAME'])"
) -join "`n"
$text = $dist.TrimEnd() + "`n`n-- ==== family\config.family.lua ====`n" + $family.TrimEnd() + "`n`n-- ==== machine settings ====`n" + $machine + "`n"
Write-Utf8NoBom (Join-Path $RepoRoot 'config.lua') $text
Write-Ok 'config.lua written'

# ---------------------------------------------------------------------------
Write-Step "Starting login-server on port $loginPort"
# ---------------------------------------------------------------------------
$loginEnv = @{
	MYSQL_HOST = $cfg['DB_HOST']; MYSQL_PORT = $cfg['DB_PORT']; MYSQL_DBNAME = $cfg['DB_NAME']
	MYSQL_USER = $cfg['DB_USER']; MYSQL_PASS = $cfg['DB_PASSWORD']
	LOGIN_HTTP_PORT = $cfg['LOGIN_HTTP_PORT']; LOGIN_GRPC_PORT = '9090'
	SERVER_IP = $cfg['SERVER_IP']; SERVER_NAME = $cfg['SERVER_NAME']; SERVER_PORT = '7172'; SERVER_LOCATION = 'BRA'
}
# The child process inherits these; they are removed from this session right after.
foreach ($k in $loginEnv.Keys) { Set-Item -Path "Env:$k" -Value $loginEnv[$k] }
try {
	$startArgs = @{ FilePath = $LoginExe; WorkingDirectory = $BinDir; PassThru = $true }
	if ($PSVersionTable.PSEdition -eq 'Desktop' -or $IsWindows) { $startArgs['WindowStyle'] = 'Minimized' }
	$login = Start-Process @startArgs
} finally {
	foreach ($k in $loginEnv.Keys) { Remove-Item -Path "Env:$k" -ErrorAction SilentlyContinue }
}
Start-Sleep -Seconds 2
if ($login.HasExited) { Stop-Family 'login-server stopped right after starting. Run family\bin\login-server.exe manually to see the error.' }
Write-Ok "login-server running (PID $($login.Id)); client URL: http://$($cfg['SERVER_IP'])$(if ($loginPort -ne 80) { ":$loginPort" })/login.php"

# ---------------------------------------------------------------------------
Write-Step 'Starting Canary (Ctrl+C here to save and stop)'
# ---------------------------------------------------------------------------
$canary = Start-Process -FilePath $CanaryExe -WorkingDirectory $RepoRoot -NoNewWindow -PassThru
try {
	while (-not $canary.HasExited) { Start-Sleep -Milliseconds 500 }
} finally {
	# Ctrl+C reaches Canary too; wait for its clean shutdown before stopping login-server.
	if (-not $canary.HasExited) { $canary.WaitForExit() }
	if (-not $login.HasExited) { Stop-Process -Id $login.Id -Force -ErrorAction SilentlyContinue }
	Write-Host 'Server stopped.' -ForegroundColor Green
}
