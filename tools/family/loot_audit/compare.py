"""Compare our monster loot with TibiaWiki (BR) and write the additions.

Inputs:
  wiki_loot.json         collected by add.py
  ITEMS (argv[1])        tab-separated dump of the server's items: id, name,
                         plural, stackable (from a test server; not committed)
Outputs:
  report.md              per creature: added, only in our files, not matched
  ../../../data/scripts/family/loot_updates_data.lua   the additions
"""
import json, os, re, sys, glob
from collections import defaultdict, Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
ITEMS = sys.argv[1]
FLAGS = sys.argv[2]  # id <tab> appearance flag numbers (18 = can be picked up)

takeable = set()
for line in open(FLAGS):
    i, _, f = line.rstrip("\n").partition("\t")
    if "18" in f.split(","):
        takeable.add(int(i))

# Chance (1/100000) given to an added item, by TibiaWiki rarity.
RARITY_CHANCE = {
    "sempre": 100000,
    "comum": 33000,
    "incomum": 10000,
    "semi-raro": 2800,
    "raro": 900,
    "muito raro": 200,
}

byname = defaultdict(set)
names = {}
stack = {}
for line in open(ITEMS, encoding="utf-8", errors="replace"):
    p = line.rstrip("\n").split("\t")
    if len(p) < 4:
        continue
    i = int(p[0]); n = p[1].lower(); pl = p[2].lower()
    names[i] = n; stack[i] = p[3] == "1"
    byname[n].add(i)
    if pl:
        byname[pl].add(i)

def block(s, key):
    i = s.find(key)
    if i < 0:
        return None
    j = s.index("{", i); d = 0
    for k in range(j, len(s)):
        if s[k] == "{": d += 1
        elif s[k] == "}":
            d -= 1
            if d == 0:
                return s[j + 1:k]

ours = {}
used_ids = defaultdict(Counter)  # name -> ids used in monster files
for f in glob.glob(os.path.join(ROOT, "data-otservbr-global/monster/**/*.lua"), recursive=True):
    s = open(f, encoding="utf-8", errors="replace").read()
    mt = re.search(r'createMonsterType\("([^"]+)"', s)
    if not mt:
        continue
    lb = block(s, "monster.loot") or ""
    items = []
    for e in re.finditer(r"\{([^{}]*)\}", lb):
        body = e.group(1)
        nm = re.search(r'name\s*=\s*"([^"]+)"', body); idm = re.search(r"\bid\s*=\s*(\d+)", body)
        if idm:
            iid = int(idm.group(1)); n = names.get(iid, "")
            if n:
                used_ids[n][iid] += 1
            items.append(n or str(iid))
        elif nm:
            items.append(nm.group(1).lower())
    ours[mt.group(1).lower()] = {"name": mt.group(1), "items": set(items), "file": os.path.relpath(f, ROOT)}

import unicodedata

def plain(text):
    return "".join(c for c in unicodedata.normalize("NFKD", text) if not unicodedata.combining(c))

def candidates(wname):
    w = plain(wname).lower().strip()
    w = re.sub(r"\s*\(.*?\)$", "", w)
    yield w
    m = re.match(r"^(\w+?)s of (.+)$", w)
    if m:
        yield m.group(1) + " of " + m.group(2)
    m = re.match(r"^(.+?) of (.+?)s$", w)
    if m:
        yield m.group(1) + " of " + m.group(2)
    if w.endswith("ies"):
        yield w[:-3] + "y"
    if w.endswith("es"):
        yield w[:-2]
    if w.endswith("s"):
        yield w[:-1]
    if w.endswith("ves"):
        yield w[:-3] + "f"
        yield w[:-3] + "fe"

def resolve(wname):
    """our item name for a wiki item name, or None"""
    for c in candidates(wname):
        if c in byname:
            ids = byname[c]
            # prefer the singular name of the item
            for i in sorted(ids):
                if names[i] == c:
                    return c
            return names[sorted(ids)[0]]
    return None

def item_ref(n):
    """loot reference for an item name: id when the name is ambiguous;
    None when no item of that name can be picked up"""
    ids = sorted(i for i in byname.get(n, ()) if names[i] == n and i in takeable)
    if not ids:
        return None
    if len(ids) == 1 and len([i for i in byname.get(n, ()) if names[i] == n]) == 1:
        return {"name": n}
    used = [i for i, _ in used_ids[n].most_common() if i in ids]
    return {"id": used[0] if used else ids[0], "comment": n}

wiki = json.load(open(os.path.join(HERE, "wiki_loot.json")))
report = ["# Loot audit against TibiaWiki (BR)", "",
          "Generated by compare.py. Added = on TibiaWiki, missing in our files (added at startup by "
          "data/scripts/family/loot_updates.lua). Only ours = in our files, not on TibiaWiki (kept). "
          "Event and raid drops are ignored.", ""]
additions = {}
stats = Counter()
for wname in sorted(wiki):
    w = wiki[wname]
    o = ours.get(wname.lower()) or ours.get(re.sub(r"\s*\(.*?\)$", "", wname).lower())
    if not o:
        stats["not in server"] += 1
        continue
    if w.get("status") != "ok" and not w["loot"]:
        stats[w.get("status", "?")] += 1
        continue
    stats["compared"] += 1
    wiki_items = {}
    unmatched = []
    for e in w["loot"]:
        r = e["rarity"].lower()
        if "durante" in r or "evento" in r or "invas" in r:
            continue
        n = resolve(e["item"])
        if not n:
            unmatched.append(e["item"])
            continue
        wiki_items[n] = e
    add = []
    for n, e in wiki_items.items():
        if n in o["items"]:
            continue
        rarity = e["rarity"].lower().replace("_", " ")
        chance = RARITY_CHANCE.get(rarity)
        if chance is None:
            unmatched.append(e["item"] + " (rarity " + e["rarity"] + ")")
            continue
        q = re.findall(r"\d+", e["qty"])
        entry = item_ref(n)
        if entry is None:
            unmatched.append(e["item"] + " (no item to pick up)")
            continue
        entry["chance"] = chance
        if q and max(int(x) for x in q) > 1:
            entry["maxCount"] = max(int(x) for x in q)
        entry["rarity"] = e["rarity"]
        add.append(entry)
    only = sorted(i for i in o["items"] if i not in wiki_items and i not in ("tibia coins",))
    if add:
        additions[o["name"]] = add
        stats["creatures with additions"] += 1
        stats["items added"] += len(add)
    if add or only or unmatched:
        report.append("## " + o["name"])
        report.append("")
        report.append("TibiaWiki: " + w["url"])
        if add:
            report.append("- Added: " + ", ".join((a.get("comment") or a.get("name")) + " (" + a["rarity"] + ")" for a in add))
        if only:
            report.append("- Only ours: " + ", ".join(only))
        if unmatched:
            report.append("- Not matched: " + ", ".join(unmatched))
        report.append("")
report[4:4] = ["Summary: " + ", ".join("%s %d" % kv for kv in sorted(stats.items())), ""]
open(os.path.join(HERE, "report.md"), "w").write("\n".join(report) + "\n")

lua = ["-- Generated by tools/family/loot_audit/compare.py from TibiaWiki (BR). Do not edit by hand.",
       "-- Items TibiaWiki lists for a creature that our creature files do not have.",
       "return {"]
for name in sorted(additions):
    lua.append('\t["%s"] = {' % name.replace('"', '\\"'))
    for a in additions[name]:
        parts = []
        if "id" in a:
            parts.append("id = %d" % a["id"])
        else:
            parts.append('name = "%s"' % a["name"].replace('"', '\\"'))
        parts.append("chance = %d" % a["chance"])
        if "maxCount" in a:
            parts.append("maxCount = %d" % a["maxCount"])
        comment = " -- " + a["comment"] if "comment" in a else ""
        lua.append("\t\t{ %s },%s" % (", ".join(parts), comment))
    lua.append("\t},")
lua.append("}")
open(os.path.join(ROOT, "data/scripts/family/loot_updates_data.lua"), "w").write("\n".join(lua) + "\n")
print(dict(stats))
