-- Ground lists -> lookup tables.
local GROUND, NEAR = {}, {}
do
	local ok, data = pcall(dofile, CORE_DIRECTORY .. "/scripts/family/mount_terrain_data.lua")
	if ok and type(data) == "table" then
		for terrain, ids in pairs(data.ground or {}) do
			for _, id in ipairs(ids) do
				GROUND[id] = terrain
			end
		end
		for terrain, ids in pairs(data.near or {}) do
			for _, id in ipairs(ids) do
				NEAR[id] = terrain
			end
		end
	else
		logger.error("[Family] mount terrain: could not read the ground lists: {}", tostring(data))
	end
end

-- Mount client id (outfit lookMount) -> mount id. Built on first use, when
-- data/XML/mounts.xml is surely loaded.
local BY_CLIENT
local function byClient(clientId)
	if not BY_CLIENT then
		BY_CLIENT = {}
		for id in pairs(Family.mountTerrainMounts) do
			local mount = Mount(id)
			if mount then
				BY_CLIENT[mount:getClientId()] = id
			end
		end
	end
	return BY_CLIENT[clientId]
end

local function groundTerrain(position)
	local tile = Tile(position)
	local ground = tile and tile:getGround()
	return ground and ground:getId() or 0
end

-- Set of terrains of a square: { wild = true, water = true, ... }.
function Family.mountTerrainAt(position)
	local terrains = {}
	local own = GROUND[groundTerrain(position)]
	if not own then
		return terrains
	end
	if (own == "wild" or own == "town") and position.z > 7 then
		own = "caves"
	end
	terrains[own] = true
	local r = Family.mountTerrain.nearRadius
	for dx = -r, r do
		for dy = -r, r do
			if dx ~= 0 or dy ~= 0 then
				local near = NEAR[groundTerrain(Position(position.x + dx, position.y + dy, position.z))]
				if near then
					terrains[near] = true
				end
			end
		end
	end
	return terrains
end

-- Surface square with nothing above it (no roof, floor, wall or bridge on
-- any higher floor; roofs are often walls or roof pieces, not ground).
function Family.mountTerrainOpenSky(position)
	if position.z > 7 then
		return false
	end
	for z = position.z - 1, 0, -1 do
		local tile = Tile(Position(position.x, position.y, z))
		if tile and tile:getThingCount() > 0 then
			return false
		end
	end
	return true
end

-- Mount id, its terrains ("sky" or {home, related}) and display name, or nil.
local function currentMount(player)
	local outfit = player:getOutfit()
	local id = outfit and outfit.lookMount and outfit.lookMount ~= 0 and byClient(outfit.lookMount)
	if not id then
		return nil
	end
	return id, Family.mountTerrainMounts[id]
end

-- Returns bonus share (0, related, home), the terrain that gave it, and its kind.
function Family.mountTerrainBonus(player)
	local config = Family.mountTerrain
	if not config.enabled then
		return 0
	end
	local id, terrains = currentMount(player)
	if not id then
		return 0
	end
	local position = player:getPosition()
	if terrains == "sky" then
		if Family.mountTerrainOpenSky(position) then
			return config.home, "sky", "home", id
		end
		return 0, nil, nil, id
	end
	local here = Family.mountTerrainAt(position)
	if here[terrains[1]] then
		return config.home, terrains[1], "home", id
	elseif here[terrains[2]] then
		return config.related, terrains[2], "related", id
	end
	return 0, nil, nil, id
end

-- Live state per player id: { delta = speed added, key = last bonus, said = { key = time } }.
Family.mountTerrainState = Family.mountTerrainState or {}
local state = Family.mountTerrainState

local function mountName(id)
	local mount = Mount(id)
	local name = mount and mount:getName() or "mount"
	return (name:gsub("%s*%b()$", "")) -- without the terrain note
end

local function update(player)
	local cid = player:getId()
	local s = state[cid]
	if not s then
		s = { delta = 0, said = {} }
		state[cid] = s
	end
	local share, terrain, kind, id = Family.mountTerrainBonus(player)
	local delta = 0
	if share > 0 then
		delta = math.floor(player:getBaseSpeed() * share)
	end
	if delta ~= s.delta then
		player:changeSpeed(delta - s.delta)
		s.delta = delta
	end
	local key = terrain and (id .. ":" .. terrain) or nil
	if key and key ~= s.key then
		local now = os.time()
		if not s.said[key] or now - s.said[key] >= Family.mountTerrain.messageCooldown then
			s.said[key] = now
			local text
			if kind == "home" then
				text = string.format("Your %s feels at home %s: +%d%% speed.", mountName(id), PLACE[terrain], math.floor(share * 100 + 0.5))
			else
				text = string.format("Your %s likes %s: +%d%% speed.", mountName(id), LIKES[terrain], math.floor(share * 100 + 0.5))
			end
			player:sendTextMessage(MESSAGE_STATUS, text)
		end
	end
	s.key = key
end

Family.mountTerrainUpdate = update

local startup = GlobalEvent("FamilyMountTerrainStartup")

function startup.onStartup()
	local grounds, mounts, sky = 0, 0, 0
	for _ in pairs(GROUND) do
		grounds = grounds + 1
	end
	for _, t in pairs(Family.mountTerrainMounts) do
		mounts = mounts + 1
		if t == "sky" then
			sky = sky + 1
		end
	end
	local c = Family.mountTerrain
	logger.info("[Family] mount terrain: {} (+{}% home, +{}% related; {} mounts, {} flying; {} grounds)", c.enabled and "on" or "off", math.floor(c.home * 100 + 0.5), math.floor(c.related * 100 + 0.5), mounts, sky, grounds)
	return true
end

startup:register()

local tick = GlobalEvent("FamilyMountTerrain")

function tick.onThink(interval)
	for _, player in ipairs(Game.getPlayers()) do
		update(player)
	end
	return true
end

tick:interval(Family.mountTerrain.interval)
tick:register()

-- Speed is not saved: start every session from zero.
local login = CreatureEvent("FamilyMountTerrainLogin")

function login.onLogin(player)
	state[player:getId()] = { delta = 0, said = {} }
	return true
end

login:register()

local logout = CreatureEvent("FamilyMountTerrainLogout")

function logout.onLogout(player)
	state[player:getId()] = nil
	return true
end

logout:register()

-- !mounts: your mounts and where they are fast.
local function describe(terrains)
	if terrains == "sky" then
		return "open sky +" .. math.floor(Family.mountTerrain.home * 100 + 0.5) .. "%"
	end
	return string.format("%s +%d%%, %s +%d%%", LABEL[terrains[1]], math.floor(Family.mountTerrain.home * 100 + 0.5), LABEL[terrains[2]], math.floor(Family.mountTerrain.related * 100 + 0.5))
end

local mountsHelp = TalkAction("!mounts", "!mount")

function mountsHelp.onSay(player, words, param)
	local lines = {
		"MOUNTS AND TERRAIN",
		"",
		string.format("Every mount is +%d%% faster on its home terrain", math.floor(Family.mountTerrain.home * 100 + 0.5)),
		string.format("and +%d%% on a related one (of your base speed).", math.floor(Family.mountTerrain.related * 100 + 0.5)),
		"Flying and floating mounts are at home under the",
		"open sky: on the surface with no roof above.",
		"The outfit window shows it: Water Buffalo (Swamp/Water)",
		"= home Swamp, related Water.",
		"",
		"Water     shallow water, sea floor, 2 sqm from the sea",
		"Swamp     mud, slime, 2 sqm from swamp water",
		"Desert    sand and dry ground",
		"Snow      snow and ice",
		"Volcanic  lava ground, burnt soil, 2 sqm from lava",
		"Wild      grass, forest, jungle, dirt, rock",
		"Caves     wild or town ground below sea level",
		"Town      roads, pavements, floors",
	}
	local id, terrains = currentMount(player)
	if id then
		lines[#lines + 1] = ""
		lines[#lines + 1] = string.format("RIDING: %s (%s)", mountName(id), describe(terrains))
		local share, terrain = Family.mountTerrainBonus(player)
		if share > 0 then
			lines[#lines + 1] = string.format("Here: +%d%% (%s)", math.floor(share * 100 + 0.5), LABEL[terrain])
		else
			lines[#lines + 1] = "Here: no bonus"
		end
	end
	local own = {}
	for mountId, t in pairs(Family.mountTerrainMounts) do
		if player:hasMount(mountId) then
			own[#own + 1] = string.format("  %s: %s", mountName(mountId), describe(t))
		end
	end
	table.sort(own)
	lines[#lines + 1] = ""
	lines[#lines + 1] = string.format("YOUR MOUNTS (%d)", #own)
	if #own == 0 then
		lines[#lines + 1] = "  none yet"
	end
	for _, line in ipairs(own) do
		lines[#lines + 1] = line
	end
	player:showTextDialog(2821, table.concat(lines, "\n"))
	return true
end

