-- Gaia Family server: mounts are faster on their own terrain (2026-10-19).
-- Ours, not upstream. Asked by Rodrigo: every mount gets a speed bonus where
-- it belongs (a Manta Ray in water, a Water Buffalo in the swamp...).
--
-- Every mount has a home terrain (+30% speed) and a related one (+15%).
-- Flying and floating mounts are at home under the open sky: anywhere on the
-- surface with nothing above (no roof, no floor). Bonuses only: no mount is
-- slower anywhere. The percentage is of the character's base speed (level),
-- and walking speed grows a bit less than speed (Tibia's step formula), so
-- +30% speed is about +20% steps per second.
--
-- Terrains (ground lists in mount_terrain_data.lua, generated by
-- tools/family/mount_terrain/classify.py from the map's grounds):
--   water     shallow water, the sea floor, and land up to 2 squares from
--             the sea or a lake (coasts, beaches, river banks)
--   swamp     mud, slime, lily pads, and land up to 2 squares from swamp water
--   desert    sand and dry ground (deserts, beaches, sandy caves)
--   snow      snow and ice
--   volcanic  lava ground, burnt soil, and land up to 2 squares from lava
--   wild      grass, forest, jungle, open dirt, rock and gravel
--   caves     wild or town ground below sea level (floor 8 and deeper)
--   town      roads, pavements and floors of buildings
--   sky       (flying mounts only) the surface with nothing overhead
-- A square can be several terrains at once (a grass shore is wild and water).
--
-- A message tells you when your mount starts to feel at home (or likes the
-- place). The mount names in data/XML/mounts.xml carry the terrains, so the
-- outfit window shows them, e.g. "Water Buffalo (Swamp/Water)", and !mounts
-- lists your mounts with their terrains.
--
-- Switch: Family.mountTerrain.enabled (false = no bonus, applied within a
-- quarter of a second).

